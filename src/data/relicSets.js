export const ALL_SETS = [...RELIC_SETS, ...ORNAMENT_SETS];
export const SET_BY_ID = Object.fromEntries(ALL_SETS.map(s => [s.id, s]));

// 遺物の部位 → どちらのセット種別か
export const SLOT_TYPE = {
  head: "relic", hands: "relic", body: "relic", feet: "relic",
  sphere: "ornament", rope: "ornament",
};

// ---- セット数カウント ----
// relics: relics.js の遺物オブジェクト配列（setId を持つ）
export function countSets(relics) {
  const count = {};
  for (const r of relics) {
    if (!r.setId) continue;
    count[r.setId] = (count[r.setId] ?? 0) + 1;
  }
  return count;
}

// 発動中のセット効果一覧 [{ set, pieces }]
export function activeSets(relics) {
  const count = countSets(relics);
  const out = [];
  for (const [id, n] of Object.entries(count)) {
    const set = SET_BY_ID[id];
    if (!set) continue;
    const pieces = set.pieces.filter(p => n >= p);
    if (pieces.length) out.push({ set, pieces });
  }
  return out;
}

// 無条件で乗る数値だけを合算（条件付き効果は含まない）
export function sumSetStaticBonuses(relics) {
  const total = {};
  const add = (obj) => {
    for (const [k, v] of Object.entries(obj ?? {})) total[k] = (total[k] ?? 0) + v;
  };
  for (const { set, pieces } of activeSets(relics)) {
    if (pieces.includes(2)) add(set.bonus2);
    if (pieces.includes(4)) add(set.static4);
  }
  return total;
}
